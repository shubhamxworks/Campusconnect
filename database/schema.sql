CREATE TABLE IF NOT EXISTS users (
  user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  google_subject VARCHAR(191) UNIQUE,
  email VARCHAR(254) NOT NULL UNIQUE,
  display_name VARCHAR(120) NOT NULL,
  password_hash VARCHAR(255),
  role VARCHAR(20) NOT NULL DEFAULT 'student'
    CHECK (role IN ('student', 'organizer', 'judge', 'admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_sessions (
  session_id VARCHAR(128) PRIMARY KEY,
  expires_at BIGINT NOT NULL,
  session_data TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_user_sessions_expires_at ON user_sessions (expires_at);

CREATE TABLE IF NOT EXISTS events (
  event_id VARCHAR(100) PRIMARY KEY,
  organizer_id BIGINT REFERENCES users (user_id) ON DELETE SET NULL,
  results_published_at TIMESTAMPTZ,
  title VARCHAR(180) NOT NULL,
  category VARCHAR(60) NOT NULL,
  summary VARCHAR(300) NOT NULL,
  description TEXT NOT NULL,
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  registration_deadline TIMESTAMPTZ NOT NULL,
  venue VARCHAR(180) NOT NULL,
  format VARCHAR(40) NOT NULL,
  organizer VARCHAR(160) NOT NULL,
  capacity INTEGER NOT NULL CHECK (capacity > 0),
  tags JSONB NOT NULL,
  artwork VARCHAR(40) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_events_time_range CHECK (ends_at >= starts_at)
);
CREATE INDEX IF NOT EXISTS idx_events_organizer ON events (organizer_id);
CREATE INDEX IF NOT EXISTS idx_events_starts_at ON events (starts_at);
CREATE INDEX IF NOT EXISTS idx_events_category_starts_at ON events (category, starts_at);

CREATE TABLE IF NOT EXISTS registrations (
  registration_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id VARCHAR(100) NOT NULL REFERENCES events (event_id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  status VARCHAR(20) NOT NULL DEFAULT 'registered'
    CHECK (status IN ('registered', 'waitlisted', 'cancelled', 'attended')),
  registered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_registrations_event_user UNIQUE (event_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_registrations_user_status ON registrations (user_id, status);

CREATE TABLE IF NOT EXISTS notifications (
  notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  event_id VARCHAR(100) REFERENCES events (event_id) ON DELETE SET NULL,
  notification_type VARCHAR(40) NOT NULL CHECK (notification_type IN (
    'registration_confirmed', 'waitlisted', 'registration_cancelled',
    'waitlist_promoted', 'results_published'
  )),
  title VARCHAR(180) NOT NULL,
  message VARCHAR(500) NOT NULL,
  read_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_notifications_user_created ON notifications (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_notifications_user_unread ON notifications (user_id, read_at, created_at);

CREATE TABLE IF NOT EXISTS web_push_subscriptions (
  subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  endpoint_hash CHAR(64) NOT NULL UNIQUE,
  endpoint VARCHAR(2048) NOT NULL,
  p256dh_key VARCHAR(255) NOT NULL,
  auth_key VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_web_push_user ON web_push_subscriptions (user_id);

CREATE TABLE IF NOT EXISTS admin_audit_logs (
  audit_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT REFERENCES users (user_id) ON DELETE SET NULL,
  action VARCHAR(100) NOT NULL,
  target_type VARCHAR(60) NOT NULL,
  target_id VARCHAR(120) NOT NULL,
  details JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_admin_audit_created ON admin_audit_logs (created_at);
CREATE INDEX IF NOT EXISTS idx_admin_audit_actor ON admin_audit_logs (actor_id, created_at);

CREATE TABLE IF NOT EXISTS teams (
  team_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id VARCHAR(100) NOT NULL REFERENCES events (event_id) ON DELETE CASCADE,
  team_name VARCHAR(50) NOT NULL,
  invitation_code CHAR(32) NOT NULL UNIQUE,
  created_by BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_teams_id_event UNIQUE (team_id, event_id)
);
CREATE INDEX IF NOT EXISTS idx_teams_event ON teams (event_id);

CREATE TABLE IF NOT EXISTS team_members (
  team_id BIGINT NOT NULL,
  event_id VARCHAR(100) NOT NULL,
  user_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (team_id, user_id),
  CONSTRAINT uq_team_members_event_user UNIQUE (event_id, user_id),
  CONSTRAINT fk_team_members_team_event
    FOREIGN KEY (team_id, event_id) REFERENCES teams (team_id, event_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_team_members_user ON team_members (user_id);

CREATE TABLE IF NOT EXISTS submissions (
  submission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id VARCHAR(100) NOT NULL,
  team_id BIGINT NOT NULL,
  submitted_by BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  project_name VARCHAR(100) NOT NULL,
  description TEXT NOT NULL,
  repository_url VARCHAR(2048) NOT NULL DEFAULT '',
  demo_url VARCHAR(2048) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_submissions_event_team UNIQUE (event_id, team_id),
  CONSTRAINT fk_submissions_team_event
    FOREIGN KEY (team_id, event_id) REFERENCES teams (team_id, event_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS event_judges (
  event_id VARCHAR(100) NOT NULL REFERENCES events (event_id) ON DELETE CASCADE,
  judge_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  assigned_by BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (event_id, judge_id)
);
CREATE INDEX IF NOT EXISTS idx_event_judges_judge ON event_judges (judge_id);

CREATE TABLE IF NOT EXISTS evaluations (
  evaluation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id BIGINT NOT NULL REFERENCES submissions (submission_id) ON DELETE CASCADE,
  judge_id BIGINT NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  score SMALLINT NOT NULL CHECK (score BETWEEN 0 AND 100),
  feedback TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_evaluations_submission_judge UNIQUE (submission_id, judge_id)
);
CREATE INDEX IF NOT EXISTS idx_evaluations_judge ON evaluations (judge_id);

CREATE OR REPLACE FUNCTION campusconnect_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE
  table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['users', 'events', 'registrations', 'web_push_subscriptions', 'submissions', 'evaluations']
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON %I', 'trg_' || table_name || '_updated_at', table_name);
    EXECUTE format(
      'CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION campusconnect_set_updated_at()',
      'trg_' || table_name || '_updated_at',
      table_name
    );
  END LOOP;
END;
$$;

